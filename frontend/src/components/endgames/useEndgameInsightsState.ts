import { useCallback, useEffect } from 'react';
import {
  useCachedEndgameInsights,
  useEndgameInsights,
  useEndgameInsightsGenerating,
} from '@/hooks/useEndgameInsights';
import { useActiveJobs } from '@/hooks/useImport';
import type {
  EndgameInsightsResponse,
  InsightsGenerateState,
  SectionId,
} from '@/types/insights';

export type SectionInsight = { headline: string; bullets: string[] } | null;
type InsightsBySection = Record<SectionId, SectionInsight>;

// The cached-report fetch (its dataUpdatedAt) that last triggered an auto-generate.
// Module-level on purpose: the Stats tab mounts twice (desktop + mobile), and both
// instances must agree that one empty cache result is worth exactly one LLM call.
// A failed auto-generate therefore does not retry on remount; only a refetched
// (still empty) cache result arms the next attempt.
let autoGeneratedForFetch: number | null = null;

// ── Endgame Insights state ───────────────────────────────────────────────────
// Mutation state lives here so per-section slots in each H2 can observe the
// same report without a context provider.
//
// The report is filter-free: one report per user, rendered whatever the
// page filter state. The cached-report query is the single source of truth:
// Generate writes its result into it (useEndgameInsights onSuccess), so the
// report survives tab remounts. The server serves the latest report even after
// newer imports; refreshing it is the user's explicit "Update Insights" click.
// Generate never reads or resets filters.
//
// Only the FIRST report is generated automatically,
// i.e. when the server has no report at all (cache 404 -> null). Once per empty
// cache result, never while an import runs or another Generate is in flight,
// and only when `autoGenerate` says the user has ranked games to narrate.
export function useEndgameInsightsState({ autoGenerate }: { autoGenerate: boolean }) {
  const insightsMutation = useEndgameInsights();
  const { data: activeJobs } = useActiveJobs(true);
  const hasActiveImport = (activeJobs?.length ?? 0) > 0;

  // Auto-load the user's previously-cached report. GET /insights/endgame/cached
  // never invokes the LLM and never consumes rate-limit budget, so it is safe to
  // fire on mount. On a 404 (no cache row), the hook resolves to null silently.
  const cachedInsights = useCachedEndgameInsights();

  // Pending in either mount: the other instance may own the in-flight request.
  const anyGenerating = useEndgameInsightsGenerating();

  const { mutateAsync } = insightsMutation;
  const handleGenerateInsights = useCallback(async () => {
    try {
      await mutateAsync();
    } catch {
      // Error is surfaced via insightsMutation.isError -> EndgameInsightsBlock error state.
      // Global MutationCache.onError in lib/queryClient.ts captures Sentry; do not
      // add a local capture here (would double-report).
    }
  }, [mutateAsync]);

  const cacheIsEmpty = cachedInsights.isSuccess && cachedInsights.data === null;
  const cacheFetchedAt = cachedInsights.dataUpdatedAt;
  useEffect(() => {
    // anyGenerating first: an in-flight request (either mount) must not consume the
    // once-per-fetch budget, and a duplicate POST would pay for a second LLM call.
    if (!autoGenerate || !cacheIsEmpty || hasActiveImport || anyGenerating) return;
    if (autoGeneratedForFetch === cacheFetchedAt) return;
    autoGeneratedForFetch = cacheFetchedAt;
    void handleGenerateInsights();
  }, [
    autoGenerate,
    cacheIsEmpty,
    cacheFetchedAt,
    hasActiveImport,
    anyGenerating,
    handleGenerateInsights,
  ]);

  const insights: EndgameInsightsResponse | null = cachedInsights.data ?? null;

  // Lookup for O(1) per-slot access during render. Null for sections the
  // backend did not return, or while the last Generate attempt failed.
  const insightBySection: InsightsBySection = {
    overall: null,
    metrics_elo: null,
    time_pressure: null,
    type_breakdown: null,
  };
  if (insights && !insightsMutation.isError) {
    for (const section of insights.report.sections) {
      insightBySection[section.section_id] = {
        headline: section.headline,
        bullets: section.bullets,
      };
    }
  }

  const generateState: InsightsGenerateState = {
    isPending: insightsMutation.isPending || anyGenerating,
    isError: insightsMutation.isError,
  };

  return { generateState, insights, handleGenerateInsights, insightBySection };
}
